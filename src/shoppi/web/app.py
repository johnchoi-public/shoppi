"""FastAPI web app: calendar REST API, streaming chat endpoint, and the static UI.

`create_app` takes its dependencies (calendar, agent, timezone) as arguments, so
tests inject fakes and the app never imports a concrete provider. `build_app`
wires the real ones from configuration; run it with:

    uvicorn shoppi.web.app:build_app --factory

Time convention: like the LLM tools, the API speaks *local naive* times in the
user's configured timezone (e.g. 2026-11-06T15:00:00). The browser never has to
deal with UTC offsets or DST; the server attaches the zone (see localtime.py).

Security: there is no authentication. This is a single-user MVP and must only
be served on localhost (the run script binds 127.0.0.1).
"""

from __future__ import annotations

import json
from collections.abc import Iterator
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from fastapi import FastAPI, HTTPException, Response
from fastapi.responses import FileResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles
from langchain_core.messages import AIMessage
from pydantic import BaseModel, Field, NaiveDatetime, ValidationError, model_validator

from shoppi.calendar.base import CalendarProvider
from shoppi.calendar.localtime import event_to_local_dict, localize
from shoppi.calendar.models import EventCreate, EventUpdate

STATIC_DIR = Path(__file__).parent / "static"


# ---- Request bodies (local naive times) -----------------------------------------


class EventIn(BaseModel):
    title: str = Field(min_length=1)
    start: NaiveDatetime
    end: NaiveDatetime
    description: str | None = None
    location: str | None = None

    @model_validator(mode="after")
    def _end_after_start(self) -> "EventIn":
        if self.end <= self.start:
            raise ValueError("end must be after start")
        return self


class EventPatch(BaseModel):
    title: str | None = Field(default=None, min_length=1)
    start: NaiveDatetime | None = None
    end: NaiveDatetime | None = None
    description: str | None = None
    location: str | None = None


class ChatIn(BaseModel):
    message: str = Field(min_length=1)
    # Generated by the browser per page load; keys the agent's conversation memory.
    thread_id: str = Field(min_length=1, max_length=100)


def _sse(payload: dict) -> str:
    """Format one Server-Sent Events message."""
    return f"data: {json.dumps(payload)}\n\n"


# ---- App ------------------------------------------------------------------------


def create_app(calendar: CalendarProvider, agent, tz: ZoneInfo) -> FastAPI:
    app = FastAPI(title="shoppi")

    @app.get("/")
    def index() -> FileResponse:
        return FileResponse(STATIC_DIR / "index.html")

    @app.get("/api/config")
    def config() -> dict:
        # The UI shows times in this zone, which may differ from the browser's.
        return {"timezone": tz.key}

    # -- Events: thin layer over CalendarProvider --

    @app.get("/api/events")
    def list_events(start: datetime, end: datetime, q: str | None = None) -> list[dict]:
        if start.tzinfo or end.tzinfo:
            raise HTTPException(422, "start/end must be local times without a UTC offset")
        events = calendar.list_events(localize(start, tz), localize(end, tz), q)
        return [event_to_local_dict(e, tz) for e in events]

    @app.post("/api/events", status_code=201)
    def create_event(body: EventIn) -> dict:
        data = body.model_dump()
        data["start"], data["end"] = localize(body.start, tz), localize(body.end, tz)
        return event_to_local_dict(calendar.create_event(EventCreate(**data)), tz)

    @app.patch("/api/events/{event_id}")
    def update_event(event_id: str, body: EventPatch) -> dict:
        data = body.model_dump(exclude_none=True)
        for key in ("start", "end"):
            if key in data:
                data[key] = localize(data[key], tz)
        try:
            return event_to_local_dict(calendar.update_event(event_id, EventUpdate(**data)), tz)
        except KeyError:
            raise HTTPException(404, "event not found")
        except (ValueError, ValidationError) as e:
            raise HTTPException(422, str(e))

    @app.delete("/api/events/{event_id}", status_code=204)
    def delete_event(event_id: str) -> Response:
        try:
            calendar.delete_event(event_id)
        except KeyError:
            raise HTTPException(404, "event not found")
        return Response(status_code=204)

    # -- Chat: stream the agent's run as Server-Sent Events --

    @app.post("/api/chat")
    def chat(body: ChatIn) -> StreamingResponse:
        def events() -> Iterator[str]:
            config = {"configurable": {"thread_id": body.thread_id}}
            try:
                # "messages" mode yields model output token by token;
                # "updates" mode yields each finished graph step (tool calls/results).
                for mode, chunk in agent.stream(
                    {"messages": [("user", body.message)]}, config, stream_mode=["messages", "updates"]
                ):
                    if mode == "messages":
                        msg, meta = chunk
                        # Streaming models yield AIMessageChunk tokens; non-streaming
                        # ones yield one whole AIMessage (AIMessageChunk subclasses it).
                        if isinstance(msg, AIMessage) and msg.content and meta.get("langgraph_node") == "model":
                            yield _sse({"type": "token", "text": msg.content})
                        continue
                    for node, update in chunk.items():
                        for msg in (update or {}).get("messages", []):
                            for call in getattr(msg, "tool_calls", None) or []:
                                yield _sse({"type": "tool_call", "name": call["name"], "args": call["args"]})
                            if node == "tools":
                                yield _sse({"type": "tool_result", "name": msg.name, "content": str(msg.content)})
            except Exception as e:  # surface model/provider failures in the chat panel
                yield _sse({"type": "error", "message": f"{type(e).__name__}: {e}"})
            yield _sse({"type": "done"})

        # A sync generator is run in Starlette's threadpool, so blocking model and
        # provider calls don't stall the event loop.
        return StreamingResponse(events(), media_type="text/event-stream")

    app.mount("/static", StaticFiles(directory=STATIC_DIR), name="static")
    return app


def build_app() -> FastAPI:
    """Wire real dependencies from configuration (for `uvicorn --factory`)."""
    from shoppi.agent.build import build_agent
    from shoppi.calendar.factory import build_calendar
    from shoppi.config import get_settings
    from shoppi.knowledge.chroma_store import ChromaDocumentStore
    from shoppi.knowledge.embeddings import build_embeddings
    from shoppi.llm.factory import build_chat_model

    s = get_settings()
    calendar = build_calendar(s)
    documents = ChromaDocumentStore(s.vector_dir, build_embeddings(s))
    agent = build_agent(build_chat_model(s), calendar, documents, s.tz)
    return create_app(calendar, agent, s.tz)
